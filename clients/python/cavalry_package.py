"""The build backend of the Python client's package, `cavalry-client`.

Generated by clients/generate.py; do not edit by hand, `just lint` regenerates and compares.
`pyproject.toml` beside this file names it, so any PEP 517 frontend builds the wheel:

    python3 -m pip wheel --no-deps --no-index --wheel-dir target/package clients/python

and so does this file run as a program, where there is no pip:

    python3 clients/python/cavalry_package.py target/package

The wheel holds the package `cavalry`, the two generated files, and beside them the
shared library the package loads, `libcavalry_ffi`, where `cavalry.find_library` looks
first (clients/python/README.md, "The package"; ADR 0166). The library is the one at
`CAVALRY_FFI_LIBRARY` when that is set, else `target/release/libcavalry_ffi` of the
checkout this file sits in, which `cargo build --release -p cavalry-ffi --lib` writes.

A wheel with a native library inside is for one platform, and its file name says which.
The tag is read from the library itself, never from the machine that builds: the least
macOS a Mach-O library says it runs on, or the newest glibc symbol version an ELF
library needs. A library this file cannot read, or cannot name a platform for, is
refused, and no wheel is written. There is no source distribution: the library is Rust,
and a source distribution would hold none.

The entries are written in one order with one timestamp, so one library and one
package give one wheel, whichever of the two ways builds it. Python 3.9 standard
library only.
"""

import base64
import hashlib
import os
import re
import struct
import sys
import zipfile

NAME = "cavalry-client"
VERSION = "0.1.0"
SUMMARY = "The Python client of Cavalry, a brokerless, low-latency message transport: ctypes over its C ABI."
REQUIRES_PYTHON = ">=3.9"
LICENSE = "Apache-2.0"
REPOSITORY = "https://github.com/appshapes/cavalry"

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = ("cavalry/__init__.py", "cavalry/_abi.py")
HELP = "see clients/python/README.md#the-package"

_ELF_MACHINES = {62: "x86_64", 183: "aarch64"}
_MACHO_CPUS = {0x0100000C: "arm64", 0x01000007: "x86_64"}
_ET_DYN = 3
_SHT_GNU_VERNEED = 0x6FFFFFFE
_MH_DYLIB = 6
_LC_VERSION_MIN_MACOSX = 0x24
_LC_BUILD_VERSION = 0x32
_PLATFORM_MACOS = 1


class PackageError(Exception):
    """The wheel was not built: the message says why and what to do next."""


class UnsupportedOperation(Exception):
    """PEP 517's name for a hook's answer that the backend cannot build that kind of
    distribution; a frontend looks it up on the backend by this name."""


def library_path():
    """The library the wheel will hold: `CAVALRY_FFI_LIBRARY` when set, else the
    checkout's `target/release/libcavalry_ffi`."""
    path = os.environ.get("CAVALRY_FFI_LIBRARY")
    if path:
        if not os.path.isfile(path):
            raise PackageError(f"CAVALRY_FFI_LIBRARY is set to {path}, and no file is there; set it to the path of "
                               f"libcavalry_ffi, or unset it to take the checkout's target/release; {HELP}")
        return path
    suffix = ".dylib" if sys.platform == "darwin" else ".so"
    path = os.path.normpath(os.path.join(HERE, "..", "..", "target", "release", "libcavalry_ffi" + suffix))
    if not os.path.isfile(path):
        raise PackageError(f"no library to put in the package: {path} does not exist and CAVALRY_FFI_LIBRARY is "
                           f"not set. Build it with `cargo build --release -p cavalry-ffi --lib` in the checkout, "
                           f"or set CAVALRY_FFI_LIBRARY to the library's path, which a frontend that copies this "
                           f"directory before it builds needs (pip before 21.3 does); {HELP}")
    return path


def _elf_platform(data, path):
    """`("libcavalry_ffi.so", "manylinux_X_Y_<machine>")` for a 64-bit little-endian ELF
    library: X.Y is the newest `GLIBC_X.Y` among the symbol versions its version-needs
    section asks of the libraries it loads, so the oldest glibc it runs on (PEP 600). An
    entry's offset to the next is followed, and an offset of zero ends a list whatever
    its count says."""
    if data[4:6] != b"\x02\x01":
        raise PackageError(f"{path} is an ELF file that is not 64-bit little-endian, and this backend has a tag "
                           f"for x86_64 and aarch64 alone; build cavalry-ffi for one of them; {HELP}")
    try:
        kind, machine = struct.unpack_from("<HH", data, 16)
        if kind != _ET_DYN:
            raise PackageError(f"{path} is an ELF file of type {kind}, not a shared library (3), and the package "
                               f"loads a shared library; point CAVALRY_FFI_LIBRARY at the libcavalry_ffi.so that "
                               f"`cargo build --release -p cavalry-ffi --lib` wrote; {HELP}")
        section_offset, = struct.unpack_from("<Q", data, 40)
        section_size, section_count = struct.unpack_from("<HH", data, 58)
        if machine not in _ELF_MACHINES:
            raise PackageError(f"{path} is an ELF library for machine {machine}, and this backend has a tag for "
                               f"x86_64 (62) and aarch64 (183) alone; build cavalry-ffi for one of them; {HELP}")
        sections = [struct.unpack_from("<IIQQQQII", data, section_offset + index * section_size)
                    for index in range(section_count)]
        newest = None
        for _, kind, _, _, offset, _, link, count in sections:
            if kind != _SHT_GNU_VERNEED:
                continue
            strings = sections[link][4]
            for _ in range(count):
                _, aux_count, _, aux, following = struct.unpack_from("<HHIII", data, offset)
                at = offset + aux
                for _ in range(aux_count):
                    _, _, _, name, aux_following = struct.unpack_from("<IHHII", data, at)
                    end = data.index(b"\0", strings + name)
                    version = re.fullmatch(rb"GLIBC_(\d+)\.(\d+)(?:\.\d+)?", data[strings + name:end])
                    if version is not None:
                        found = (int(version.group(1)), int(version.group(2)))
                        newest = found if newest is None or found > newest else newest
                    if aux_following == 0:
                        break
                    at += aux_following
                if following == 0:
                    break
                offset += following
    except (struct.error, IndexError, ValueError) as error:
        raise PackageError(f"{path} could not be read as an ELF library ({error}); build it again with `cargo "
                           f"build --release -p cavalry-ffi --lib`; {HELP}") from None
    if newest is None:
        raise PackageError(f"{path} asks for no GLIBC symbol version, so it was not linked against glibc, and this "
                           f"backend has a tag for glibc's Linux alone (manylinux); build cavalry-ffi for a "
                           f"`-linux-gnu` target; {HELP}")
    return "libcavalry_ffi.so", f"manylinux_{newest[0]}_{newest[1]}_{_ELF_MACHINES[machine]}"


def _macho_platform(data, path):
    """`("libcavalry_ffi.dylib", "macosx_X_Y_<cpu>")` for a 64-bit Mach-O library: X.Y is
    the least macOS its build-version load command says it runs on. A tag has no place
    for a version's third number, and from macOS 11 on an installer knows the tags
    `macosx_<major>_0` alone. So a least version that a tag cannot say is written as the
    next one it can, the first that does not promise a system the library refuses:
    10.9.5 as 10_10, 11.0.1 and 11.3 as 12_0."""
    try:
        cpu, _, kind, command_count = struct.unpack_from("<iiII", data, 4)
        cpu &= 0xFFFFFFFF
        if kind != _MH_DYLIB:
            raise PackageError(f"{path} is a Mach-O file of type {kind}, not a dynamic library (6), and the package "
                               f"loads a dynamic library; point CAVALRY_FFI_LIBRARY at the libcavalry_ffi.dylib "
                               f"that `cargo build --release -p cavalry-ffi --lib` wrote; {HELP}")
        if cpu not in _MACHO_CPUS:
            raise PackageError(f"{path} is a Mach-O library for cpu type {cpu:#x}, and this backend has a tag for "
                               f"arm64 and x86_64 alone; build cavalry-ffi for one of them; {HELP}")
        least = None
        at = 32
        for _ in range(command_count):
            command, size = struct.unpack_from("<II", data, at)
            if size < 8:
                raise ValueError(f"a load command of {size} bytes")
            if command == _LC_BUILD_VERSION:
                platform, version = struct.unpack_from("<II", data, at + 8)
                if platform == _PLATFORM_MACOS:
                    least = version
            elif command == _LC_VERSION_MIN_MACOSX:
                least, = struct.unpack_from("<I", data, at + 8)
            at += size
    except (struct.error, ValueError) as error:
        raise PackageError(f"{path} could not be read as a Mach-O library ({error}); build it again with `cargo "
                           f"build --release -p cavalry-ffi --lib`; {HELP}") from None
    if least is None:
        raise PackageError(f"{path} names no least macOS version, so it was not built for macOS, and this backend "
                           f"has a tag for macOS alone among Apple's systems; build cavalry-ffi for an "
                           f"`-apple-darwin` target; {HELP}")
    major, minor, patch = least >> 16, (least >> 8) & 0xFF, least & 0xFF
    if major >= 11:
        major, minor = (major, 0) if (minor, patch) == (0, 0) else (major + 1, 0)
    elif patch:
        minor += 1
    return "libcavalry_ffi.dylib", f"macosx_{major}_{minor}_{_MACHO_CPUS[cpu]}"


def library_platform(data, path):
    """The library's file name in the package and the wheel's platform tag, both read
    from the library's own bytes."""
    if data[:4] == b"\x7fELF":
        return _elf_platform(data, path)
    if data[:4] == b"\xcf\xfa\xed\xfe":
        return _macho_platform(data, path)
    raise PackageError(f"{path} is neither an ELF library nor a 64-bit Mach-O library of one architecture, and "
                       f"this backend packages Linux and macOS alone; point CAVALRY_FFI_LIBRARY at the "
                       f"libcavalry_ffi.so or libcavalry_ffi.dylib that cargo wrote; {HELP}")


def _metadata():
    return (f"Metadata-Version: 2.1\nName: {NAME}\nVersion: {VERSION}\nSummary: {SUMMARY}\n"
            f"License: {LICENSE}\nProject-URL: Repository, {REPOSITORY}\nRequires-Python: {REQUIRES_PYTHON}\n")


def build_wheel(wheel_directory, config_settings=None, metadata_directory=None):
    """PEP 517's hook: write the wheel into `wheel_directory` and return its file name."""
    path = library_path()
    with open(path, "rb") as f:
        library = f.read()
    library_name, platform = library_platform(library, path)
    tag = f"py3-none-{platform}"
    distribution = f"{NAME.replace('-', '_')}-{VERSION}"
    info = f"{distribution}.dist-info"
    entries = []
    for source in SOURCES:
        with open(os.path.join(HERE, source), "rb") as f:
            entries.append((source, f.read(), 0o644))
    entries.append((f"cavalry/{library_name}", library, 0o755))
    try:
        with open(os.path.join(HERE, "LICENSE"), "rb") as f:
            entries.append((f"{info}/LICENSE", f.read(), 0o644))
    except FileNotFoundError:
        raise PackageError(f"{os.path.join(HERE, 'LICENSE')} does not exist, and the wheel carries the licence; "
                           f"`python3 clients/generate.py python` in a checkout writes it; {HELP}") from None
    entries.append((f"{info}/METADATA", _metadata().encode(), 0o644))
    entries.append((f"{info}/WHEEL", (f"Wheel-Version: 1.0\nGenerator: cavalry_package {VERSION}\n"
                                      f"Root-Is-Purelib: false\nTag: {tag}\n").encode(), 0o644))
    record = "".join(f"{name},sha256={base64.urlsafe_b64encode(hashlib.sha256(content).digest()).rstrip(b'=').decode()}"
                     f",{len(content)}\n" for name, content, _ in entries) + f"{info}/RECORD,,\n"
    entries.append((f"{info}/RECORD", record.encode(), 0o644))
    os.makedirs(wheel_directory, exist_ok=True)
    wheel = f"{distribution}-{tag}.whl"
    with zipfile.ZipFile(os.path.join(wheel_directory, wheel), "w", zipfile.ZIP_DEFLATED) as archive:
        for name, content, mode in entries:
            entry = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            entry.external_attr = (0o100000 | mode) << 16
            archive.writestr(entry, content)
    return wheel


def get_requires_for_build_wheel(config_settings=None):
    """PEP 517's hook: the build needs nothing installed."""
    return []


def build_sdist(sdist_directory, config_settings=None):
    """PEP 517's hook for a source distribution, which this package does not have."""
    raise UnsupportedOperation(f"{NAME} has no source distribution: its wheel holds libcavalry_ffi, which cargo builds from "
                       f"the Rust in a checkout. Build the wheel alone, `python3 -m pip wheel --no-deps clients/python` "
                       f"or `python3 -m build --wheel clients/python`; {HELP}")


def main(argv):
    if len(argv) != 2:
        sys.stderr.write("usage: cavalry_package.py <directory to write the wheel into>\n")
        return 2
    try:
        print(os.path.join(argv[1], build_wheel(argv[1])))
    except PackageError as error:
        sys.stderr.write(f"cavalry_package: {error}\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
